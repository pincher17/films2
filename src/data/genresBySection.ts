/**
 * Жанры по разделам каталога.
 *
 * В TMDB у фильмов и сериалов разные системы жанров: у сериалов нет
 * «триллера», «ужасов», «фантастики» — вместо них «нф и фэнтези», а
 * «боевик» и «приключения» объединены в один жанр. Поэтому у каждого
 * раздела свой список, и подменять жанры больше не нужно.
 *
 * `value` — то, что уходит на сервер (русское название из TMDB),
 * `id` — порядковый номер для интерфейса.
 */

export type GenreOption = { value: string; label: string; id: number };

const make = (names: string[]): GenreOption[] =>
  names.map((name, index) => ({ value: name, label: name, id: index + 1 }));

/** Фильмы: 19 жанров TMDB */
export const movieGenres = make([
  "боевик",
  "приключения",
  "вестерн",
  "военный",
  "детектив",
  "документальный",
  "драма",
  "история",
  "комедия",
  "криминал",
  "мелодрама",
  "музыка",
  "мультфильм",
  "семейный",
  "телевизионный фильм",
  "триллер",
  "ужасы",
  "фантастика",
  "фэнтези",
]);

/** Сериалы: 16 жанров TMDB */
export const tvGenres = make([
  "боевик и приключения",
  "вестерн",
  "война и политика",
  "детектив",
  "детский",
  "документальный",
  "драма",
  "комедия",
  "криминал",
  "мультфильм",
  "мыльная опера",
  "новости",
  "нф и фэнтези",
  "реалити-шоу",
  "семейный",
  "ток-шоу",
]);

/** Мультфильмы: тот же жанр «мультфильм», но с уточнениями по типу */
export const cartoonGenres = make([
  "мультфильм",
  "семейный",
  "комедия",
  "приключения",
  "фэнтези",
  "фантастика",
  "драма",
  "детский",
]);

/** Какой список показывать в фильтрах для раздела */
export function genresForSection(section: "movies" | "series" | "cartoons"): GenreOption[] {
  if (section === "series") return tvGenres;
  if (section === "cartoons") return cartoonGenres;
  return movieGenres;
}
