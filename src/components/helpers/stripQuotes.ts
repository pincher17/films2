/**
 * Снимает кавычки по краям строки.
 *
 * Нужно для слоганов: TMDB отдаёт их иногда уже в кавычках («Не стоит
 * встречаться со своими героями»), а страница оборачивает слоган в «» сама —
 * получалось ««…»». Снимаем все виды кавычек, какие встречаются в данных:
 * типографские, английские, немецкие, программные.
 */
const QUOTES = /^[\s«»"„“”'‘’]+|[\s«»"„“”'‘’]+$/g;

export default function stripQuotes(value?: string | null) {
  if (!value) return '';
  return String(value).replace(QUOTES, '').trim();
}
