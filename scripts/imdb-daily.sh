#!/bin/sh
# Ночная сборка соответствий TMDB ↔ IMDb.
#
# Две части:
#   1. imdbmap.mjs — закрывает очередь трейлеров (новые задачи появляются
#      каждый день, поэтому проход нужен постоянно);
#   2. imdb-coverage.mjs — идёт по каталогу TMDB: популярное, новинки по дате,
#      затем по годам вглубь. Размеченное пропускается, поэтому с каждым
#      запуском скрипт забирается всё дальше и покрытие растёт.
#      Глубину подняли 04.11: 500 страниц популярного, 50 новинок, 30 страниц
#      на год, бюджет 150 минут (~40 тыс. проверок за ночь).
#
# Ошибка в первой части не должна мешать второй, поэтому без set -e.

cd /var/www/filmhub || exit 1

/usr/bin/node scripts/imdbmap.mjs 5000
/usr/bin/node scripts/imdb-coverage.mjs --popular 500 --fresh 50 --years 30 --minutes 150
