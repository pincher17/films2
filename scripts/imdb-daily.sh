#!/bin/sh
# Ночная сборка соответствий TMDB ↔ IMDb и рейтингов IMDb.
#
# Три части:
#   1. imdbmap.mjs — закрывает очередь трейлеров (новые задачи появляются
#      каждый день, поэтому проход нужен постоянно);
#   2. imdb-coverage.mjs — идёт по каталогу TMDB: популярное, новинки по дате,
#      затем по годам вглубь. Размеченное пропускается, поэтому с каждым
#      запуском скрипт забирается всё дальше и покрытие растёт.
#      Глубину подняли 04.11: 500 страниц популярного, 50 новинок, 30 страниц
#      на год, бюджет 150 минут (~40 тыс. проверок за ночь).
#   3. Рейтинги IMDb из официального датасета — после соответствий, чтобы
#      свежие сопоставления сразу получили оценку. Датасет обновляется
#      ежедневно; замер на сервере: 8,7 МБ, 17 секунд, ~60 тыс. строк.
#
# Ошибка в одной части не должна мешать остальным, поэтому без set -e.

cd /var/www/filmhub || exit 1

/usr/bin/node scripts/imdbmap.mjs 5000
/usr/bin/node scripts/imdb-coverage.mjs --popular 500 --fresh 50 --years 30 --minutes 150

# Рейтинги: если датасет не скачался, работаем на прошлых оценках
RATINGS_FILE=/tmp/ratings.tsv.gz
if curl -fsSL --max-time 600 -o "$RATINGS_FILE" https://datasets.imdbws.com/title.ratings.tsv.gz; then
  /usr/bin/node scripts/imdb-ratings.mjs "$RATINGS_FILE"
else
  echo "[ratings] не удалось скачать датасет — оценки остаются прошлыми"
fi
